/**
 * Display names for tables that were created without a paid custom name.
 *
 * A user-set name (the optional "Table Name" field, poker-vm#337) is always
 * shown as stored. Otherwise the name is derived from a FNV-1a 64-bit hash of
 * the full table id, so every player sees the same name and it stays put
 * across reloads. Bit 0 chooses two words or three. Three non-overlapping
 * 16-bit slices pick the words.
 *
 * Order is poker, then crypto, then an optional degen word, so names read
 * like "river-whale" or "river-whale-yolo": the game, the stake, the vibe.
 *
 * Display only. This module never writes a table id or any on-chain field.
 */

