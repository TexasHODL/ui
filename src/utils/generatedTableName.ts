export const GENERATED_TABLE_NAME_LIST_SIZE = 200;

const FNV_OFFSET = 0xcbf29ce484222325n;
const FNV_PRIME = 0x100000001b3n;
const FNV_MASK = 0xffffffffffffffffn;
const WORD_SLICE_BITS = 16n;

/** FNV-1a 64-bit over UTF-16 code units. Pure and stable across engines. */
function fnv1a64(value: string): bigint {
    let hash = FNV_OFFSET;
    for (let i = 0; i < value.length; i++) {
        hash ^= BigInt(value.charCodeAt(i));
        hash = (hash * FNV_PRIME) & FNV_MASK;
    }
    return hash;
}

function pick(hash: bigint, shift: bigint, words: readonly string[]): string {
    const index = Number((hash >> shift) % BigInt(words.length));
    return words[index];
}

/**
 * Lowercase hyphenated name for an unnamed table, e.g. "river-whale" or
 * "river-whale-yolo". Hashes the full table id, not a truncated suffix.
 */
export function generateTableName(tableId: string): string {
    const hash = fnv1a64(tableId);
    const pokerWord = pick(hash, 1n, TABLE_NAME_POKER);
    const cryptoWord = pick(hash, 1n + WORD_SLICE_BITS, TABLE_NAME_CRYPTO);
    if ((hash & 1n) === 0n) {
        return `${pokerWord}-${cryptoWord}`;
    }
    const degenWord = pick(hash, 1n + WORD_SLICE_BITS * 2n, TABLE_NAME_DEGEN);
    return `${pokerWord}-${cryptoWord}-${degenWord}`;
}

/**
 * Name to render. A non-blank custom name wins; surrounding whitespace is
 * trimmed and the rest is shown unchanged. Otherwise the generated name.
 */
export function displayTableName(customName: string | null | undefined, tableId: string): string {
    const custom = customName?.trim();
    if (hasContent(custom)) {
        return custom;
    }
    return generateTableName(tableId);
}
